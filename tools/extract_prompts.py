#!/usr/bin/env python3
"""Write instructor/prompts.txt: every prompt on the Explore page, word for word, in page order.

    python3 tools/extract_prompts.py

Students copy prompts from the page; the run sheet, the deck and the video's scenes must use the same words. Run this
after changing a prompt, and diff the file to see what changed.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
page = (ROOT / "site" / "explore.qmd").read_text(encoding="utf-8")
out = []
blocks = re.finditer(r"(?:^|\n)(#{2,3} [^\n]*)|::: \{\.prompt\}\n```default\n(.*?)\n```\n:::", page, re.S)
current, n = "", 0
for m in blocks:
    if m.group(1):
        current = re.sub(r"<[^>]+>", "", m.group(1).lstrip("# ")).split("{")[0].strip()
    else:
        n += 1
        out.append(f"## {n}. {current}\n\n{m.group(2).strip()}\n")
(ROOT / "instructor" / "prompts.txt").write_text(
    "# Every prompt on the Explore page, in order. Generated by tools/extract_prompts.py; don't edit.\n\n"
    + "\n".join(out), encoding="utf-8")
print(f"{n} prompts written to instructor/prompts.txt")
