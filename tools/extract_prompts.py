#!/usr/bin/env python3
"""Write what's built from the page's prompts.

    python3 tools/extract_prompts.py

    instructor/prompts.txt        every prompt on the page, in page order, word for word as students copy it
    site/_describe-anatomy.md     the describe prompt cut into numbered parts: the "what's in this prompt" figure

Students copy prompts from the page, so the run sheet and the figure must use the same words. Both outputs take their
numbers from site/_variables.yml. Run this after changing a prompt, and diff prompts.txt to see what changed.
tools/make_data.py runs it too, after it rewrites the variables.
"""
import html
import re
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "site" / "index.qmd"


def variables() -> dict:
    """site/_variables.yml as {"data.rows": "12,569", ...}. The file is flat enough to read without a YAML library."""
    out, top = {}, ""
    for line in (ROOT / "site" / "_variables.yml").read_text(encoding="utf-8").splitlines():
        m = re.match(r'^(\s*)([\w-]+):\s*(?:"((?:[^"\\]|\\.)*)")?', line)
        if not m:
            continue
        indent, key, value = m.groups()
        if value is not None:
            value = value.replace('\\"', '"')
        if not indent:
            top = key
            if value is not None:
                out[key] = value
        elif value is not None:
            out[f"{top}.{key}"] = value
    return out


VARS = variables()


def resolve(text: str) -> str:
    """Put the variables' values where the page has {{< var ... >}}."""
    def value(m):
        if m.group(1) not in VARS:
            raise SystemExit(f"{m.group(1)} is used in a prompt but isn't in site/_variables.yml")
        return VARS[m.group(1)]
    return re.sub(r"\{\{<\s*var\s+([\w.-]+)\s*>\}\}", value, text)


def anatomy(prompt: str) -> str:
    """The describe prompt as a figure: six numbered parts, in the prompt's own words."""
    paragraphs = prompt.split("\n\n")
    if len(paragraphs) != 5:
        raise SystemExit(f"The describe prompt has {len(paragraphs)} paragraphs; the figure expects 5.")
    intro, layout, table, notes, how = paragraphs
    sentences = re.split(r"(?<=\.)\s+(?=[A-Z])", layout)
    if len(sentences) != 3:
        raise SystemExit(f"The describe prompt's layout paragraph has {len(sentences)} sentences; the figure expects 3.")
    where, row, lead = sentences
    parts = [(1, intro), (2, where), (3, row), (None, lead), (4, table), (5, notes), (6, how)]
    squeeze = lambda s: re.sub(r"\s+", " ", s).strip()
    assert squeeze(" ".join(text for _, text in parts)) == squeeze(prompt), "the figure's parts don't add up to the prompt"
    lines = ["<!-- Generated by tools/extract_prompts.py from the describe prompt in index.qmd. Don't edit. -->", "",
             "```{=html}",
             '<figure class="anatomy" role="group" aria-label="The describe prompt, cut into six numbered parts">']
    for number, text in parts:
        tag = "pre" if text is table else "p"
        badge = (f'<span class="num" aria-hidden="true">{number}</span>'
                 f'<span class="visually-hidden">Part {number}: </span>') if number else ""
        lines.append(f'<div class="part{"" if number else " plain"}">{badge}<{tag}>{html.escape(text, quote=False)}'
                     f'</{tag}></div>')
    lines += ["</figure>", "```", ""]
    return "\n".join(lines)


page = PAGE.read_text(encoding="utf-8")
out, prompts = [], []
blocks = re.finditer(r"(?:^|\n)(#{1,3} [^\n]*)|[ \t]*::: \{\.prompt\}\n[ \t]*```default\n(.*?)\n[ \t]*```\n[ \t]*:::",
                     page, re.S)
current = ""
for m in blocks:
    if m.group(1):
        current = re.sub(r"<[^>]+>", "", m.group(1).lstrip("# ")).split("{")[0].strip()
    else:
        text = resolve(textwrap.dedent(m.group(2)).strip())
        prompts.append(text)
        out.append(f"## {len(prompts)}. {current}\n\n{text}\n")

(ROOT / "instructor" / "prompts.txt").write_text(
    "# Every prompt on the page, in order, as students copy it. Generated by tools/extract_prompts.py; don't edit.\n\n"
    + "\n".join(out), encoding="utf-8")
print(f"{len(prompts)} prompts written to instructor/prompts.txt")

describe = prompts[0]
if "made-up rows" not in describe:
    raise SystemExit("The first prompt on the page should be the describe prompt.")
(ROOT / "site" / "_describe-anatomy.md").write_text(anatomy(describe), encoding="utf-8")
print("the describe prompt's figure written to site/_describe-anatomy.md")
